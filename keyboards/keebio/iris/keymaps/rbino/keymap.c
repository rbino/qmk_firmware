// clang-format on

bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    switch (keycode) {
        case QWERTY:
            if (record->event.pressed) {
                set_single_persistent_default_layer(_QWERTY);
            }
            return false;
            break;
        case MAC:
            if (record->event.pressed) {
                layer_invert(_MAC);
                rgblight_enable_noeeprom();
                rgblight_mode_noeeprom(RGBLIGHT_MODE_STATIC_LIGHT);

                if (layer_state_is(_MAC)) {
                  rgblight_sethsv_noeeprom(HSV_RED);
                } else {
                  rgblight_sethsv_noeeprom(HSV_GREEN);
                }
            }
            return false;
            break;
        case LOWER:
            if (record->event.pressed) {
                layer_on(_LOWER);
                if (layer_state_is(_MAC)) {
                  layer_on(_MAC_LOWER);
                }
                update_tri_layer(_LOWER, _RAISE, _ADJUST);
            } else {
                layer_off(_MAC_LOWER);
                layer_off(_LOWER);
                update_tri_layer(_LOWER, _RAISE, _ADJUST);
            }
            return false;
            break;
        case RAISE:
            if (record->event.pressed) {
                layer_on(_RAISE);
                if (layer_state_is(_MAC)) {
                  layer_on(_MAC_RAISE);
                }
                update_tri_layer(_LOWER, _RAISE, _ADJUST);
            } else {
                layer_off(_MAC_RAISE);
                layer_off(_RAISE);
                update_tri_layer(_LOWER, _RAISE, _ADJUST);
            }
            return false;
            break;
        case ADJUST:
            if (record->event.pressed) {
                layer_on(_ADJUST);
            } else {
                layer_off(_ADJUST);
            }
            return false;
            break;
    }
    return true;
}

bool encoder_update_user(uint8_t index, bool clockwise) {
    if (index == 0) {
        if (clockwise) {
            tap_code(KC_VOLU);
        } else {
            tap_code(KC_VOLD);
        }
    } else if (index == 1) {
        if (clockwise) {
            tap_code(KC_PGDN);
        } else {
            tap_code(KC_PGUP);
        }
    }
    return false;
}
